class IgnoreExtraFieldsModel(BaseModel):
    model_config = ConfigDict(extra="ignore", populate_by_name=True)


class StationEconomy(IgnoreExtraFieldsModel):
    name: str
    share: float


class StationNamedItem(IgnoreExtraFieldsModel):
    name: str


class StationMarketItem(IgnoreExtraFieldsModel):
    buy_price: int
    category: str
    commodity: str
    demand: int
    sell_price: int
    supply: int
    is_rare: bool | None = None


class StationModule(IgnoreExtraFieldsModel):
    category: str
    class_: int = Field(alias="class")
    ed_symbol: str
    name: str
    rating: str
    price: int | None = None
    ship: str | None = None
    weapon_mode: str | None = None


class StationShip(IgnoreExtraFieldsModel):
    name: str
    price: int
    symbol: str


